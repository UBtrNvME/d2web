import { test } from '@playwright/test';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { open } from '../../packages/d2web/tests/browser/harness.mjs';
import { root } from '../examples.mjs';

// Spec 0008: layout cost per engine in the browser, written to docs/layout-limits.md. Run with `mise run measure:layout` (minutes; not in check).
// Boards: a synthetic ladder (chain with a branching tree and back edges) and every single-file corpus board in examples/files.
const ladder = n => {
  const l = ['direction: right'];
  for (let i = 0; i < n; i++) l.push(`n${i}.label: ""`, `n${i}.width: 80`, `n${i}.height: 40`);
  for (let i = 1; i < n; i++) l.push(`n${Math.floor((i - 1) / 3)} -> n${i}`);
  for (let i = 5; i < n; i += 5) l.push(`n${i} -> n${(i * 7) % i}`);
  return l.join('\n') + '\n';
};
const BUDGET = 90_000;
const engines = ['tala', 'dagre', 'elk'];
const sizes = { tala: [10, 25, 50, 100, 150], dagre: [10, 100, 500, 1000], elk: [10, 100, 500, 1000] };

test('measure layout time per engine', async ({ page }) => {
  test.setTimeout(60 * 60_000);
  await open(page, {});
  const run = (source, layout) => page.evaluate(async ({ source, layout, budget }) => {
    const started = performance.now();
    try {
      const r = await window.compile(source, { request: { layout, budgets: { maxLayoutMillis: budget } } });
      if (r.error) return { error: r.error.code };
      const objects = r.boards[0].association.objects;
      return { ms: Math.round(performance.now() - started), shapes: objects.filter(o => o.kind !== 'connection').length, connections: objects.filter(o => o.kind === 'connection').length };
    } catch (e) { return { error: e.code === 'budget' ? `over ${budget / 1000} s` : e.constructor.name }; }
  }, { source, layout, budget: BUDGET });

  await run('warm\n', 'tala');
  const rows = [];
  for (const engine of engines) for (const n of sizes[engine]) rows.push({ engine, board: `ladder ${n}`, ...await run(ladder(n), engine) });
  const dir = join(root, 'examples/files');
  for (const name of readdirSync(dir).filter(f => f.endsWith('.d2'))) {
    const source = readFileSync(join(dir, name), 'utf8');
    if (/^\s*(?:\.\.\.)?@|\bimport\b/m.test(source)) continue; // single-file boards only
    for (const engine of engines) rows.push({ engine, board: name, ...await run(source, engine) });
  }

  const cell = r => (r?.ms !== undefined ? `${r.ms} ms` : r?.error ?? '-');
  const byBoard = new Map();
  for (const r of rows) byBoard.set(r.board, { ...byBoard.get(r.board), [r.engine]: r, size: r.shapes !== undefined ? `${r.shapes} / ${r.connections}` : byBoard.get(r.board)?.size });
  const table = [...byBoard].map(([board, v]) => `| ${board} | ${v.size ?? '-'} | ${cell(v.tala)} | ${cell(v.dagre)} | ${cell(v.elk)} |`);
  const stamp = new Date().toISOString().slice(0, 10);
  writeFileSync(join(root, 'docs/layout-limits.md'), `# Layout limits

Generated by \`mise run measure:layout\` (spec 0008) on ${stamp}: ${process.platform}/${process.arch}, ${page.context().browser().browserType().name()} ${page.context().browser().version()}, wall time of a compile through the shipping client and worker (includes protocol overhead, excludes painting). One run, one machine: use the orders of magnitude, not the digits. Runs longer than ${BUDGET / 1000} s are aborted by \`budgets.maxLayoutMillis\`. The wasm is single-threaded, so the page stays responsive but TALA's cost cannot be shared.

Size is shapes / connections as D2 counts them (\`countObjects\`). When a layout is slow, the consumer may request \`layout: 'dagre'\` or \`'elk'\` itself; they give different layouts from TALA and d2web never switches on its own.

| Board | Shapes / connections | TALA | dagre | ELK |
| --- | --- | --- | --- | --- |
${table.join('\n')}
`);
});
