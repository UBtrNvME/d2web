import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { root } from '../examples.mjs';
import { catalog } from './catalog.mjs';
import { boardTarget } from './compile.mjs';
import { families } from './families.mjs';
import { notes } from './notes.mjs';
import { webForms, byDesign } from './web-forms.mjs';
import { beyondPaint } from './beyond-paint.mjs';

// Feature map step 5: docs/feature-map.md, generated from the catalog and the last full run (artifacts/feature-map/{compile,paint}.json).
const read = name => JSON.parse(readFileSync(join(root, 'artifacts/feature-map', name), 'utf8'));
const note = id => notes.find(n => n.match.test(id))?.text ?? '';
const design = id => byDesign.find(d => d.match.test(id));
const statusOf = (id, paint) => (design(id) ? 'web-native' : paint[id]?.status ?? 'missing');
const closed = s => s === 'ok' || s === 'web-native' || s === 'equivalent';
const esc = s => String(s).replaceAll('|', '\\|').replaceAll('\n', ' ');
const difference = p => p.ratio === undefined ? esc(p.detail ?? '') : `${(100 * p.ratio).toFixed(1)} % of image, ${(100 * p.inkRatio).toFixed(0)} % of ink`;

export function writeReport() {
  const compile = Object.fromEntries(read('compile.json').map(r => [r.id, r]));
  const paint = Object.fromEntries(read('paint.json').map(r => [r.id, r]));
  const byFamily = new Map();
  for (const e of catalog) byFamily.set(e.family, [...(byFamily.get(e.family) ?? []), e]);
  const counts = {};
  const out = [];
  out.push('# D2 feature map', '',
    'Generated by `mise run test:features:paint` from [the catalog](../tests/features/catalog.mjs); do not edit by hand (notes live in `tests/features/notes.mjs`, family text in `families.mjs`). Every case is compiled by the product worker, mounted with the shipping `mount` API in Chromium and compared with D2\'s own native SVG for the same options.', '',
    '- **ok**: at most 5 % of all pixels differ (ADR 0002/0007 bar) and at most 25 % of the inked pixels differ (a stricter, proposed second bar, because a missing label hides inside a small board\'s whole-image ratio).',
    '- **web-native**: native paints a static artefact (a badge, a footnote) where the web has its own natural behaviour; the difference is intended and not counted as a gap. The rule: D2 should be natural on the web, not look like native SVG (see [the web forms](#natural-web-forms) and ADR 0009).',
    '- **equivalent**: the strict bars fail, but every differing pixel has a matching pixel within one pixel in the other image (and the same bars hold on that tolerant count): the same drawing with glyph or curve edges rasterised slightly apart. Closed, not a gap; the screenshots are kept in `artifacts/feature-map/shots`.',
    '- **differs**, **size-mismatch**: measured gaps. **no-native**: native D2 cannot render the same options. Link and tooltip behaviour (hover, click) is browser interaction and is not covered by the pixel comparison.',
    '- Mechanism: `scene-paint` arrives as scene primitives the painter draws; `compile-only` is resolved by D2 while compiling; `interaction` also needs browser behaviour.',
    '- Chromium only, one machine, offline worker (remote images become placeholders), TALA seed 1 unless the case names an engine. Every case compares root; the Boards family also compares every non-root board with the same thresholds. Extra board rows are listed separately and do not change catalog coverage or rollup counts. **missing** means not yet measured.', '');
  const rows = [];
  const forms = ['## Natural web forms', '', 'The web element or behaviour that is natural for each family (the target; the painter may not be there yet).', '', '| Family | Natural web form |', '| --- | --- |', ...Object.entries(webForms).map(([f, t]) => `| ${families[f]?.[0] ?? f} | ${esc(t)} |`), ''];
  for (const [family, entries] of byFamily) {
    const c = {};
    for (const e of entries) { const s = statusOf(e.id, paint); c[s] = (c[s] ?? 0) + 1; counts[s] = (counts[s] ?? 0) + 1; }
    rows.push(`| ${families[family]?.[0] ?? family} | ${entries.length} | ${(c.ok ?? 0) + (c['web-native'] ?? 0) + (c.equivalent ?? 0)} | ${entries.length - (c.ok ?? 0) - (c['web-native'] ?? 0) - (c.equivalent ?? 0)} |`);
  }
  const total = catalog.length;
  out.push(`## Rollup: ${(counts.ok ?? 0) + (counts['web-native'] ?? 0) + (counts.equivalent ?? 0)} of ${total} cases ok, equivalent or web-native`, '', '| Family | Cases | closed | open |', '| --- | --- | --- | --- |', ...rows, '',
    `Statuses: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(', ')}.`, '');
  out.push(...forms);
  for (const [family, entries] of byFamily) {
    const [title, text] = families[family] ?? [family, ''];
    out.push(`## ${title}`, '', text, '');
    const good = entries.filter(e => statusOf(e.id, paint) === 'ok');
    const rest = entries.filter(e => statusOf(e.id, paint) !== 'ok');
    if (good.length) out.push(`**ok (${good.length}):** ${good.map(e => `\`${e.id.split('/')[1]}\``).join(', ')}`, '');
    if (rest.length) {
      out.push('| Case | D2 | Mechanism | Primitives | Status | Difference | Note |', '| --- | --- | --- | --- | --- | --- | --- |');
      for (const e of rest) {
        const p = paint[e.id] ?? {}, c = compile[e.id] ?? {};
        out.push(`| \`${e.id.split('/')[1]}\` | \`${esc(e.source.replaceAll('\n', '; ')).slice(0, 70)}\` | ${e.mechanism} | ${(c.primitives ?? []).join(', ')} | ${statusOf(e.id, paint)} | ${difference(p)} | ${esc(design(e.id)?.text ?? note(e.id))} |`);
      }
      out.push('');
    }
    if (family === 'board') {
      out.push('Non-root boards (same pixel and ink thresholds; excluded from the catalog rollup):', '', '| Case / board | Status | Difference |', '| --- | --- | --- |');
      for (const e of entries) {
        for (const board of (compile[e.id]?.boards ?? []).filter(Boolean)) {
          const id = `${e.id}#${boardTarget(board)}`;
          out.push(`| \`${esc(id)}\` | ${statusOf(id, paint)} | ${difference(paint[id] ?? {})} |`);
        }
      }
      out.push('');
    }
  }
  out.push('## Beyond painting', '', 'D2 capabilities that are not "paint a scene". The scope column is a proposal; ADR 0007 owns what v1 includes.', '', '| Capability | What it is | Proposed scope | Note |', '| --- | --- | --- | --- |',
    ...beyondPaint.map(r => `| ${r.map(esc).join(' | ')} |`), '');
  writeFileSync(join(root, 'docs/feature-map.md'), out.join('\n') + '\n');
}
