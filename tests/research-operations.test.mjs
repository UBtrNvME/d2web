import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { test } from 'node:test';
import { root } from './examples.mjs';

test('research: native oracle mutation and text measurement keys agree with Node/WASM', { timeout: 300_000 }, () => {
  const output = join(root, 'artifacts/research-operations');
  mkdirSync(output, { recursive: true });
  const env = { ...process.env, GOCACHE: join(root, '.cache/go-build'), GOMODCACHE: join(root, '.cache/go-mod') };
  const run = (command, args, options = {}) => {
    const result = spawnSync(command, args, { cwd: join(root, 'imports/d2'), env, encoding: 'utf8', timeout: 180_000, maxBuffer: 8 * 1024 * 1024, ...options });
    assert.ifError(result.error);
    assert.equal(result.status, 0, result.stderr);
    return result.stdout;
  };
  const probe = join(root, 'tests/research-operations.go');
  const native = join(output, 'probe');
  const wasm = join(output, 'probe.wasm');
  run('go', ['build', '-mod=readonly', '-o', native, probe]);
  run('go', ['build', '-mod=readonly', '-o', wasm, probe], { env: { ...env, GOOS: 'js', GOARCH: 'wasm' } });
  const directory = join(root, 'examples/research/identity');
  const files = Object.fromEntries(readdirSync(directory).filter(file => file.endsWith('.d2')).map(file => [file, readFileSync(join(directory, file), 'utf8')]));
  const request = JSON.stringify({ entry: 'main.d2', files });
  const result = JSON.parse(run(native, [request]));
  const goRoot = run('go', ['env', 'GOROOT']).trim();
  assert.deepEqual(JSON.parse(run(join(goRoot, 'lib/wasm/go_js_wasm_exec'), [wasm, request])), result);
  const [successful, rejected, imported, scenario] = result.operations;
  assert.equal(successful.error, '');
  assert.equal(successful.returnedNil, false);
  assert.notEqual(successful.after, successful.before, 'successful native Set mutates the input AST');
  assert.match(successful.after, /#112233/);
  assert.match(rejected.error, /opacity/);
  assert.equal(rejected.returnedNil, true);
  assert.notEqual(rejected.after, rejected.before, 'semantic rejection leaves the supplied native AST changed');
  assert.match(rejected.after, /opacity: 2/);
  assert.equal(imported.error, '');
  assert.equal(imported.returnedNil, false);
  assert.equal(imported.after, imported.before.replace('*: {style.stroke: "#123456"}\n', '*: {style.stroke: "#123456"}\nimported.child.style.fill: "#112233"\n'), 'imported definition is overridden locally rather than rewritten');
  assert.equal(scenario.error, '');
  assert.equal(scenario.returnedNil, false);
  assert.deepEqual(scenario.board, ['changed']);
  assert.equal(scenario.after, scenario.before.replace('local.label: changed', 'local.label: edited'), 'scenario edit stays within its board declaration');
  assert.deepEqual(result.firstMeasurement, { width: 100, height: 20 });
  assert.deepEqual(result.secondMeasurement, result.firstMeasurement, 'equal text keys select the first premeasurement despite a distinct requested size');
  writeFileSync(join(output, 'native.json'), JSON.stringify(result, null, 2) + '\n');
  writeFileSync(join(output, 'summary.json'), JSON.stringify({ nativeAndNodeWasmEqual: true, rejectedNativeSetMutatesInputAST: true, equalTextKeysSelectFirstPremeasurement: true, scope: 'Native Go API behavior for one successful root edit, one rejected root edit, one imported-object override and one scenario edit. No persistent files modified; no browser or public editing wrapper tested.' }, null, 2) + '\n');
});
